"""Remote Mac anisette provider using the SideStore v3 protocol.

Apple now rejects GSA developer-token exchanges made with anisette generated by
the Android libraries.  The v3 services below supply only the Mac provisioning
half; SRP, Apple ID credentials, verification codes, and GSA tokens continue to
go directly from EmLoad to Apple.
"""
from __future__ import annotations

import base64
import hashlib
import json
import os
import plistlib
import re
import socket
import ssl
import time
import uuid
from dataclasses import dataclass
from datetime import datetime, timezone
from typing import Any
from urllib.parse import urlparse

import requests
from wsproto import ConnectionType, WSConnection
from wsproto.events import AcceptConnection, CloseConnection, Ping, RejectConnection, Request, TextMessage

from . import paths, tls
from .anisette import AnisetteError

SERVERS = (
    "https://mac-ani.jkcoxson.com",
    "https://new.ani.sidestore.io",
    "https://ani3.stikstore.app",
)
SERVER_ENV = "EMLOAD_ANISETTE_SERVER"
STATE_FILE = "remote-v3.json"
_TIMEOUT = 20
_MAX_FIELD = 8192
_PROVISIONING_DEADLINE = 90
_START_URL = "https://gsa.apple.com/grandslam/MidService/startMachineProvisioning"
_FINISH_URL = "https://gsa.apple.com/grandslam/MidService/finishMachineProvisioning"
_CLIENT_INFO_RE = re.compile(r"^<[^<>\r\n]{1,100}> <[^<>\r\n]{1,100}> <[^<>\r\n]{1,160}>$")


class _Unavailable(Exception):
    pass


class _NeedsProvisioning(Exception):
    pass


@dataclass(frozen=True)
class Fetched:
    headers: dict[str, str]
    client_info: str
    user_agent: str
    server: str


@dataclass
class _State:
    identifier: bytes
    adi_pb: bytes | None = None

    @classmethod
    def new(cls) -> "_State":
        return cls(os.urandom(16))

    @property
    def identifier_b64(self) -> str:
        return base64.b64encode(self.identifier).decode("ascii")

    @property
    def device_id(self) -> str:
        return str(uuid.UUID(bytes=self.identifier))

    @property
    def md_lu(self) -> str:
        return hashlib.sha256(self.identifier).hexdigest()


def _state_path():
    return paths.anisette_dir() / STATE_FILE


def _load_state() -> _State:
    try:
        raw = json.loads(_state_path().read_text(encoding="utf-8"))
        identifier = base64.b64decode(raw["identifier"], validate=True)
        if len(identifier) != 16:
            raise ValueError("invalid identifier")
        adi = raw.get("adi_pb")
        return _State(identifier, base64.b64decode(adi, validate=True) if adi else None)
    except Exception:
        return _State.new()


def _save_state(state: _State, server: str) -> None:
    path = _state_path()
    tmp = path.with_suffix(".tmp")
    tmp.write_text(json.dumps({"identifier": state.identifier_b64,
                               "adi_pb": base64.b64encode(state.adi_pb).decode("ascii") if state.adi_pb else None,
                               "server": server}), encoding="utf-8")
    tmp.replace(path)


def _header(name: str, value: Any) -> str:
    if not isinstance(value, str) or not value or len(value) > _MAX_FIELD or "\r" in value or "\n" in value:
        raise _Unavailable(f"invalid {name} returned by anisette service")
    return value


class _WebSocket:
    def __init__(self, url: str) -> None:
        parsed = urlparse(url)
        host = parsed.hostname or ""
        secure = parsed.scheme == "wss"
        try:
            raw = socket.create_connection((host, parsed.port or (443 if secure else 80)), timeout=_TIMEOUT)
            if secure:
                raw = ssl.create_default_context(cafile=tls.ca_bundle()).wrap_socket(raw, server_hostname=host)
        except OSError as exc:
            raise _Unavailable(f"cannot connect ({type(exc).__name__})") from exc
        self.sock = raw
        self.ws = WSConnection(ConnectionType.CLIENT)
        target = parsed.path or "/"
        if parsed.query:
            target += "?" + parsed.query
        self._send(self.ws.send(Request(host=parsed.netloc, target=target, extra_headers=[(b"user-agent", b"EmLoad")])))
        deadline = time.monotonic() + _TIMEOUT
        while True:
            for event in self.ws.events():
                if isinstance(event, AcceptConnection):
                    return
                if isinstance(event, RejectConnection):
                    self.close()
                    raise _Unavailable(f"WebSocket refused (HTTP {event.status_code})")
            self._receive(deadline)

    def _send(self, data: bytes) -> None:
        try:
            self.sock.sendall(data)
        except OSError as exc:
            raise _Unavailable("WebSocket connection lost") from exc

    def _receive(self, deadline: float) -> None:
        self.sock.settimeout(max(0.1, deadline - time.monotonic()))
        try:
            data = self.sock.recv(65536)
        except (OSError, TimeoutError) as exc:
            raise _Unavailable("WebSocket timed out") from exc
        if not data:
            raise _Unavailable("WebSocket closed early")
        try:
            self.ws.receive_data(data)
        except Exception as exc:
            raise _Unavailable("invalid WebSocket response") from exc

    def send_text(self, text: str) -> None:
        self._send(self.ws.send(TextMessage(data=text)))

    def recv_text(self, timeout: float) -> str | None:
        deadline, parts = time.monotonic() + timeout, []
        while time.monotonic() < deadline:
            for event in self.ws.events():
                if isinstance(event, TextMessage):
                    parts.append(event.data)
                    if sum(map(len, parts)) > _MAX_FIELD * 4:
                        raise _Unavailable("WebSocket reply too large")
                    if event.message_finished:
                        return "".join(parts)
                elif isinstance(event, Ping):
                    self._send(self.ws.send(event.response()))
                elif isinstance(event, CloseConnection):
                    return None
            self._receive(deadline)
        raise _Unavailable("WebSocket timed out")

    def close(self) -> None:
        try:
            self.sock.close()
        except OSError:
            pass


class RemoteAnisette:
    def servers(self) -> tuple[str, ...]:
        override = os.environ.get(SERVER_ENV, "").strip().rstrip("/")
        if override:
            parsed = urlparse(override)
            if parsed.scheme != "https" or not parsed.hostname:
                raise AnisetteError(f"{SERVER_ENV} must be an https:// URL")
            return (override,)
        return SERVERS

    def fetch(self) -> Fetched:
        failures = []
        for server in self.servers():
            try:
                return self._fetch(server)
            except _Unavailable as exc:
                failures.append(f"{urlparse(server).hostname}: {exc}")
        raise AnisetteError("Could not reach a Mac anisette service. Try again later.\n\nTried:\n  " + "\n  ".join(failures))

    def _json(self, method: str, url: str, body: dict[str, Any] | None = None) -> Any:
        try:
            response = requests.request(method, url, json=body, headers={"User-Agent": "EmLoad"}, timeout=_TIMEOUT, verify=tls.ca_bundle())
        except requests.RequestException as exc:
            raise _Unavailable(f"cannot connect ({type(exc).__name__})") from exc
        if response.status_code != 200:
            raise _Unavailable(f"answered HTTP {response.status_code}")
        try:
            return response.json()
        except ValueError as exc:
            raise _Unavailable("did not answer with JSON") from exc

    def _identity(self, server: str) -> tuple[str, str]:
        raw = self._json("GET", f"{server}/v3/client_info")
        if not isinstance(raw, dict):
            raise _Unavailable("client_info was not an object")
        client_info, user_agent = raw.get("client_info"), raw.get("user_agent")
        if not isinstance(client_info, str) or not client_info.isascii() or not _CLIENT_INFO_RE.fullmatch(client_info):
            raise _Unavailable("invalid client_info")
        if not isinstance(user_agent, str) or not user_agent.isascii() or not user_agent or "\r" in user_agent or "\n" in user_agent:
            raise _Unavailable("invalid user_agent")
        return client_info, user_agent

    def _fetch(self, server: str) -> Fetched:
        client_info, user_agent = self._identity(server)
        state = _load_state()
        if state.adi_pb is None:
            self._provision(server, client_info, user_agent, state)
        try:
            return self._headers(server, client_info, user_agent, state)
        except _NeedsProvisioning:
            state = _State.new()
            self._provision(server, client_info, user_agent, state)
            return self._headers(server, client_info, user_agent, state)

    def _headers(self, server: str, client_info: str, user_agent: str, state: _State) -> Fetched:
        assert state.adi_pb is not None
        raw = self._json("POST", f"{server}/v3/get_headers", {"identifier": state.identifier_b64, "adi_pb": base64.b64encode(state.adi_pb).decode("ascii")})
        if not isinstance(raw, dict):
            raise _Unavailable("get_headers was not an object")
        if raw.get("result") == "GetHeadersError":
            if "-45061" in str(raw.get("message", "")):
                raise _NeedsProvisioning
            raise AnisetteError(f"Anisette service error: {str(raw.get('message', 'unknown error'))[:300]}")
        if raw.get("result") != "Headers":
            raise _Unavailable("unexpected get_headers response")
        return Fetched({"X-Apple-I-Client-Time": datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
                        "X-Apple-I-MD": _header("X-Apple-I-MD", raw.get("X-Apple-I-MD")),
                        "X-Apple-I-MD-LU": state.md_lu,
                        "X-Apple-I-MD-M": _header("X-Apple-I-MD-M", raw.get("X-Apple-I-MD-M")),
                        "X-Apple-I-MD-RINFO": _header("X-Apple-I-MD-RINFO", raw.get("X-Apple-I-MD-RINFO")),
                        "X-Apple-I-SRL-NO": "0", "X-Mme-Device-Id": state.device_id}, client_info, user_agent, server)

    def _apple_post(self, url: str, body: dict[str, Any], client_info: str, user_agent: str, state: _State) -> dict[str, Any]:
        headers = {"Content-Type": "text/x-xml-plist", "Accept": "*/*", "Connection": "close", "User-Agent": user_agent, "X-MMe-Client-Info": client_info, "X-Apple-I-MD-LU": state.md_lu, "X-Mme-Device-Id": state.device_id}
        try:
            response = requests.post(url, data=plistlib.dumps(body), headers=headers, timeout=_TIMEOUT, verify=tls.ca_bundle())
            response.raise_for_status()
            reply = plistlib.loads(response.content).get("Response", {})
        except (requests.RequestException, ValueError) as exc:
            raise AnisetteError("Apple's device-provisioning service could not be reached.") from exc
        status = reply.get("Status", {})
        if status.get("ec", 0):
            raise AnisetteError(f"Apple provisioning error {status['ec']}: {status.get('em', '')}")
        return reply

    def _provision(self, server: str, client_info: str, user_agent: str, state: _State) -> None:
        socket_ = _WebSocket(server.replace("https://", "wss://", 1) + "/v3/provisioning_session")
        deadline = time.monotonic() + _PROVISIONING_DEADLINE
        try:
            while True:
                text = socket_.recv_text(max(0.1, deadline - time.monotonic()))
                if text is None:
                    raise _Unavailable("provisioning connection closed")
                try:
                    message = json.loads(text)
                except ValueError as exc:
                    raise _Unavailable("invalid provisioning response") from exc
                result = message.get("result") if isinstance(message, dict) else None
                if result == "GiveIdentifier":
                    socket_.send_text(json.dumps({"identifier": state.identifier_b64}))
                elif result == "GiveStartProvisioningData":
                    reply = self._apple_post(_START_URL, {"Header": {}, "Request": {}}, client_info, user_agent, state)
                    socket_.send_text(json.dumps({"spim": _header("spim", reply.get("spim"))}))
                elif result == "GiveEndProvisioningData":
                    reply = self._apple_post(_FINISH_URL, {"Header": {}, "Request": {"cpim": _header("cpim", message.get("cpim"))}}, client_info, user_agent, state)
                    socket_.send_text(json.dumps({"ptm": _header("ptm", reply.get("ptm")), "tk": _header("tk", reply.get("tk"))}))
                elif result == "ProvisioningSuccess":
                    try:
                        state.adi_pb = base64.b64decode(str(message.get("adi_pb", "")), validate=True)
                    except ValueError as exc:
                        raise _Unavailable("invalid provisioned identity") from exc
                    if not state.adi_pb:
                        raise _Unavailable("empty provisioned identity")
                    _save_state(state, server)
                    return
                elif result in ("Timeout", "InvalidIdentifier"):
                    raise _Unavailable(f"provisioning failed ({result})")
                elif result in ("StartProvisioningError", "EndProvisioningError"):
                    raise AnisetteError(f"Apple provisioning failed: {str(message.get('message', ''))[:300]}")
                else:
                    raise _Unavailable("unexpected provisioning response")
        finally:
            socket_.close()


_provider = RemoteAnisette()


def fetch() -> Fetched:
    return _provider.fetch()
